// Builds everything installable from src/ into plugins/, and rewrites the
// marketplace file and the README's table of looks.
//
//   node scripts/build.mjs
//
// Edit src/themes.js, run this, and commit the result. Everything under
// plugins/ is generated: a change made there is overwritten by the next build.

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { makeColors } from '../src/make-colors.js'
import { ORIGINALS, PALETTE_CREDITS } from '../src/credits.js'
import { LOOKS } from '../src/themes.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const AUTHOR = 'briannaworkman'
const VERSION = '0.2.0'
const GLASS = { blur: 18, opacity: 0.5 }
const BUNDLE = 'looks'

const write = (path, text) => {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
}
const json = value => JSON.stringify(value, null, 2) + '\n'

// The same backdrop the bundle draws: a vertical gradient with a faint glow in
// the upper right, as a scene, so the app frosts its panels over it.
const sceneFor = look => {
  const [top, middle, bottom] = look.sky
  const glow = typeof look.def.roles?.accent === 'string' ? look.def.roles.accent : '#ffffff'

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" preserveAspectRatio="none">
  <defs>
    <linearGradient id="fade" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${top}"/>
      <stop offset="0.5" stop-color="${middle}"/>
      <stop offset="1" stop-color="${bottom}"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.85" cy="0.15" r="0.6">
      <stop offset="0" stop-color="${glow}" stop-opacity="0.14"/>
      <stop offset="1" stop-color="${glow}" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="100" height="100" fill="url(#fade)"/>
  <rect width="100" height="100" fill="url(#glow)"/>
</svg>`
}

// A look adapted from a VS Code theme says where its colors came from.
const creditComment = look =>
  look.credit
    ? `// Colors adapted from the VS Code theme ${look.credit.extension} by ${look.credit.author}\n// (${look.credit.license}), https://github.com/${look.credit.repo}\n`
    : ''

const microRegister = (look, colors) => `import type { Register, ThemeColors } from 'claude-code'

// ${look.name}, one look of github.com/${AUTHOR}/looks.
// Generated by scripts/build.mjs from src/themes.js: change the look there.
${creditComment(look)}
const SCENE_NAME = 'look-${look.id}'

const COLORS: ThemeColors = ${JSON.stringify(colors, null, 2)}

// A scene, not a still gradient, on purpose: a scene's glass makes the app frost
// its panels over the backdrop, where a still ground leaves a solid strip behind
// the prompt box.
const SCENE = \`${sceneFor(look)}\`

export const register: Register = on => {
  on('session.start', async ($, e, next) => {
    const set = await $.theme.set({
      colors: COLORS,
      backdrop: { scene: SCENE_NAME, glass: ${JSON.stringify(GLASS)} },
    })

    if (!set.isDrawn) {
      $.ui.status(set.reason)
    }

    return next(e)
  })

  // Every plugin's hook hears the backdrop, so leave another's scene alone.
  on('ui.render', { component: 'Backdrop' }, ($, e, next) => {
    if (e.props.scene !== SCENE_NAME) {
      return next(e)
    }

    if (e.surface !== 'desktop' && e.surface !== 'mobile') {
      return next(e)
    }

    const { Svg } = $.ui.resolve(e)

    return <Svg source={SCENE} alt=${JSON.stringify(look.name + ': a soft gradient backdrop')} isInteractive />
  })
}
`

const HOOKS = { modules: ['./register.tsx'] }

// Start clean so a look removed from src/ leaves nothing behind.
rmSync(join(ROOT, 'plugins'), { recursive: true, force: true })

const entries = []
const failures = []

for (const look of LOOKS) {
  const { theme, problems } = makeColors(look.def)
  const unpainted = problems.filter(line => line.startsWith("Desktop won't paint"))

  if (unpainted.length > 0) {
    failures.push(`${look.id}: ${unpainted[0]}`)
    continue
  }
  const name = `look-${look.id}`
  const description =
    `${look.name}: a ${look.mode} theme for the Claude desktop and mobile apps.` +
    (look.credit ? ` Colors adapted from ${look.credit.extension} by ${look.credit.author} (${look.credit.license}).` : '')
  const dir = join(ROOT, 'plugins', name)

  write(join(dir, '.claude-plugin', 'plugin.json'), json({ name, version: VERSION, description, author: { name: AUTHOR } }))
  write(join(dir, 'hooks', 'hooks.json'), json(HOOKS))
  write(join(dir, 'hooks', 'register.tsx'), microRegister(look, theme))
  entries.push({ name, source: `./plugins/${name}`, description })
}

if (failures.length > 0) {
  console.error('Not built, Desktop would not paint these:\n  ' + failures.join('\n  '))
  process.exit(1)
}

// The bundle: every look and a /look switcher, with the helper files it needs.
const bundleDir = join(ROOT, 'plugins', BUNDLE)
const bundleDescription = `All ${LOOKS.length} looks for the Claude desktop and mobile apps, switched with /look.`

write(join(bundleDir, '.claude-plugin', 'plugin.json'), json({ name: BUNDLE, version: VERSION, description: bundleDescription, author: { name: AUTHOR } }))
write(join(bundleDir, 'hooks', 'hooks.json'), json(HOOKS))
cpSync(join(ROOT, 'src', 'bundle-register.tsx'), join(bundleDir, 'hooks', 'register.tsx'))

for (const file of ['make-colors.js', 'make-colors.d.ts', 'themes.js', 'themes.d.ts', 'imported.js', 'imported.d.ts']) {
  cpSync(join(ROOT, 'src', file), join(bundleDir, 'hooks', file))
}

write(
  join(ROOT, '.claude-plugin', 'marketplace.json'),
  json({
    name: 'looks',
    description: `A gallery of ${LOOKS.length} themes for the Claude desktop and mobile apps. Install them all, or just one.`,
    owner: { name: AUTHOR },
    plugins: [{ name: BUNDLE, source: `./plugins/${BUNDLE}`, description: bundleDescription }, ...entries],
  }),
)

// The README's tables, between its markers.
const originals = new Set(ORIGINALS)
const table = mode => {
  const rows = LOOKS.filter(look => look.mode === mode).map(
    look => `| \`${look.id}\` | ${look.name}${originals.has(look.id) ? ' (original)' : ''} | \`look-${look.id}\` |`,
  )

  return [
    `### ${mode === 'dark' ? 'Dark' : 'Light'} (${rows.length})`,
    '',
    '| `/look` name | Theme | Install just this one |',
    '| --- | --- | --- |',
    ...rows,
  ].join('\n')
}
const generated = `<!-- looks:start -->\n${table('dark')}\n\n${table('light')}\n<!-- looks:end -->`
const readmePath = join(ROOT, 'README.md')

if (existsSync(readmePath)) {
  const readme = readFileSync(readmePath, 'utf8')

  if (!readme.includes('<!-- looks:start -->')) {
    console.error('README.md has no <!-- looks:start --> marker, so its tables were not updated.')
    process.exit(1)
  }
  writeFileSync(
    readmePath,
    readme
      .replace(/<!-- looks:start -->[\s\S]*<!-- looks:end -->/, () => generated)
      .replace(/<!-- count:start -->\d+<!-- count:end -->/g, () => `<!-- count:start -->${LOOKS.length}<!-- count:end -->`),
  )
}

// CREDITS.md: every look's origin in one place. A look with no credit anywhere
// fails the build, so a new look cannot ship unattributed.
const adapted = LOOKS.filter(look => look.credit)
const palettes = LOOKS.filter(look => !look.credit && PALETTE_CREDITS[look.id])
const originalLooks = LOOKS.filter(look => ORIGINALS.includes(look.id))
const uncredited = LOOKS.filter(look => !look.credit && !PALETTE_CREDITS[look.id] && !ORIGINALS.includes(look.id))

if (uncredited.length > 0) {
  console.error(`No credit for: ${uncredited.map(look => look.id).join(', ')}. Add each to ORIGINALS or PALETTE_CREDITS in src/credits.js.`)
  process.exit(1)
}

write(
  join(ROOT, 'CREDITS.md'),
  [
    '# Credits',
    '',
    `Every look in this gallery and where it comes from: ${palettes.length} use published color palettes, ${adapted.length} are adapted from VS Code themes, and ${originalLooks.length} are new. This repository is not affiliated with any of these projects, and the credit for their colors belongs to their authors.`,
    '',
    '## Looks that use a published palette',
    '',
    `These ${palettes.length} use the colors of a well-known palette. The palette's name and its maker are given; see each project for its own license terms. The layout (surfaces, text steps, backdrop) is this gallery's.`,
    '',
    '| Look | Palette | Made by |',
    '| --- | --- | --- |',
    ...palettes.map(look => `| ${look.name} | ${PALETTE_CREDITS[look.id][0]} | ${PALETTE_CREDITS[look.id][1]} |`),
    '',
    '## Looks adapted from VS Code themes',
    '',
    `These ${adapted.length} are adapted from themes published as VS Code extensions. The colors were read from each theme's own published color file, and the layout is this gallery's. Each is listed with its author, its source repository and that repository's license, which was an open-source license when the look was added.`,
    '',
    '| Look | Author | Source | License |',
    '| --- | --- | --- | --- |',
    ...adapted.map(
      look =>
        `| ${look.name} | ${look.credit.author} | [${look.credit.extension}](https://github.com/${look.credit.repo}) | ${look.credit.license} |`,
    ),
    '',
    '## Original looks',
    '',
    `These ${originalLooks.length} are new, made for this gallery: ${originalLooks.map(look => look.name).join(', ')}.`,
    '',
    '## Code',
    '',
    "`src/make-colors.js` is the color helper from Claude Code's mod authoring kit, included unchanged. It keeps its own origin; it is not covered by this repository's MIT license.",
    '',
  ].join('\n'),
)

console.log(`Built ${entries.length} looks and the "${BUNDLE}" bundle into plugins/.`)
